import { Prisma, PrismaClient } from "@prisma/client";
import { env } from "../../config/env";

export async function createPromptTestDb(adminId: number) {
  const url = new URL(env.DATABASE_URL);
  const sourceSchema = url.searchParams.get("schema") ?? "public";
  url.searchParams.set("schema", "pg_temp");
  url.searchParams.set("connection_limit", "1");
  const db = new PrismaClient({ datasourceUrl: url.href });

  try {
    const schema = Prisma.raw(`"${sourceSchema.replaceAll('"', '""')}"`);
    // Bảng tạm chỉ tồn tại trên kết nối test. Dùng bộ đếm ID riêng cho fixture.
    for (const table of ["prompt_templates", "audit_logs"]) {
      const identifier = Prisma.raw(`"${table}"`);
      await db.$executeRaw`CREATE TEMP TABLE ${identifier} (LIKE ${schema}.${identifier} INCLUDING DEFAULTS INCLUDING INDEXES)`;
      await db.$executeRaw`ALTER TABLE pg_temp.${identifier} ALTER COLUMN id DROP DEFAULT`;
      await db.$executeRaw`ALTER TABLE pg_temp.${identifier} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`;
    }
    await db.$executeRaw`ALTER TABLE pg_temp.audit_logs ADD CHECK (user_id = ${Prisma.raw(String(adminId))})`;
    return db;
  } catch (error) {
    await db.$disconnect();
    throw error;
  }
}